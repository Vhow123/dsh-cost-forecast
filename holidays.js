/** 合并内置节假日与用户自填日期（去重、排序）；`auto` 为 false 时只用用户填的 */
export function effectiveHolidays(config) {
  const custom = Array.isArray(config?.peakHolidays)
    ? config.peakHolidays.filter((day) => typeof day === 'string' && /^\d{4}-\d{2}-\d{2}$/.test(day))
    : []
  if (config?.peakAutoHolidays === false) return [...new Set(custom)].sort()
  return [...new Set([...CN_HOLIDAYS, ...custom])].sort()
}

/** 内置表覆盖的年份，用于在面板上提示「今年是否已收录」 */
export function coveredYears() {
  return [...new Set(CN_HOLIDAYS.map((day) => day.slice(0, 4)))].sort()
}
